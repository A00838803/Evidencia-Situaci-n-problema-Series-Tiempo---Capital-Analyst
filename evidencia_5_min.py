# Function to fit and evaluate AR, ARMA, and ARIMA models
def fit_time_series_models(series, name, max_p=3, max_q=3):
    print(f"\nFitting Time Series Models for {name}:")

    # Store results for comparison
    models_results = []

    # Fit AR models (ARIMA with q=0, d=0)
    best_ar_aic = float('inf')
    best_ar_order = None
    for p in range(1, max_p + 1):
        try:
            model = ARIMA(series, order=(p, 0, 0))
            results = model.fit()
            models_results.append(('AR', (p, 0, 0), results.aic))
            if results.aic < best_ar_aic:
                best_ar_aic = results.aic
                best_ar_order = (p, 0, 0)
        except:
            continue

    # Fit ARMA models (ARIMA with p>0, q>0, d=0)
    best_arma_aic = float('inf')
    best_arma_order = None
    for p in range(1, max_p + 1):
        for q in range(1, max_q + 1):
            try:
                model = ARIMA(series, order=(p, 0, q))
                results = model.fit()
                models_results.append(('ARMA', (p, 0, q), results.aic))
                if results.aic < best_arma_aic:
                    best_arma_aic = results.aic
                    best_arma_order = (p, 0, q)
            except:
                continue

    # Fit ARIMA models (d=1 to account for differencing)
    best_arima_aic = float('inf')
    best_arima_order = None
    for p in range(max_p + 1):
        for q in range(max_q + 1):
            try:
                model = ARIMA(series, order=(p, 1, q))
                results = model.fit()
                models_results.append(('ARIMA', (p, 1, q), results.aic))
                if results.aic < best_arima_aic:
                    best_arima_aic = results.aic
                    best_arima_order = (p, 1, q)
            except:
                continue

    # Print model comparison
    print(f"\nModel Comparison for {name}:")
    print("Model Type | Order | AIC")
    print("-" * 30)
    for model_type, order, aic in models_results:
        print(f"{model_type:<10} | {order} | {aic:.2f}")

    # Select the best overall model
    best_model = min(models_results, key=lambda x: x[2])
    best_model_type, best_order, best_aic = best_model
    print(f"\nBest Model for {name}:")
    print(f"Type: {best_model_type}")
    print(f"Order: {best_order}")
    print(f"AIC: {best_aic:.2f}")
    print("Interpretation:")
    if best_model_type == 'AR':
        print(f"  - AR({best_order[0]}): {best_order[0]} autoregressive term(s)")
    elif best_model_type == 'ARMA':
        print(f"  - ARMA({best_order[0]},{best_order[2]}): {best_order[0]} autoregressive term(s), {best_order[2]} moving average term(s)")
    elif best_model_type == 'ARIMA':
        print(f"  - ARIMA({best_order[0]},1,{best_order[2]}): {best_order[0]} autoregressive term(s), 1 differencing, {best_order[2]} moving average term(s)")

    return best_model_type, best_order

